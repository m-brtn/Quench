#!/usr/bin/env python3
"""Writes src/render/LtcTable.inc, the fitted tables of linearly transformed cosines (LTC) for the area lights of
quench_render, from fit/results/ltc.js of selfshadow/ltc_code (BSD-2-Clause with a reference to the paper; the
licence text is in THIRD_PARTY_LICENSES):

    Real-Time Polygonal-Light Shading with Linearly Transformed Cosines.
    Eric Heitz, Jonathan Dupuy, Stephen Hill and David Neubelt.
    ACM Transactions on Graphics (Proceedings of ACM SIGGRAPH 2016) 35(4), 2016.

Usage: tools/make_ltc_table.py path/to/ltc.js [output]
(curl -LO https://raw.githubusercontent.com/selfshadow/ltc_code/<commit>/fit/results/ltc.js)

The tables are 64 x 64, x the perceptual roughness (alpha = roughness^2), y sqrt(1 - cos theta) of the view
angle. g_ltc_1 holds the inverse matrix M^-1 = [[x 0 y] [0 1 0] [z 0 w]] (columns as in the reference's GLSL), g_ltc_2
the GGX lobe's magnitude, its Fresnel term and the horizon-clipped sphere's form factor (not used: the shaders use
the analytic approximation). The values are kept as 32-bit floats: at low roughness and grazing angles the matrices'
elements go down to 1e-10, below half precision.
"""

import hashlib
import re
import sys
from pathlib import Path

COMMIT = "31e5e96b54f98f33098f8503003119ba2231a1c6"
SHA256 = "21071160163defd419b8f754ab604a8e60c44fcf539bfff9916e0e8e82316c1d"
SIZE = 64


def read_array(source: str, name: str) -> list[float]:
    match = re.search(r"var " + name + r"\s*=\s*\[(.*?)\];", source, re.S)
    if not match:
        sys.exit(f"{name} not found")
    values = [float(v) for v in match.group(1).replace("\n", " ").split(",") if v.strip()]
    if len(values) != SIZE * SIZE * 4:
        sys.exit(f"{name}: {len(values)} values, expected {SIZE * SIZE * 4}")
    return values


def literal(value: float) -> str:
    if value == 0.0:
        return "0"
    text = f"{value:.6g}"  # the source's precision
    if "e" not in text and "." not in text:
        text += ".0"
    return text + "f"


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    data = Path(sys.argv[1]).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"ltc.js SHA256 {digest}, expected {SHA256} (ltc_code {COMMIT})")
    source = data.decode()
    m = read_array(source, "g_ltc_1")
    g = read_array(source, "g_ltc_2")
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "src/render/LtcTable.inc"
    lines = [
        "// Generated by tools/make_ltc_table.py from fit/results/ltc.js of selfshadow/ltc_code",
        f"// ({COMMIT}, SHA256 {SHA256}).",
        "// Copyright (c) 2017, Eric Heitz, Jonathan Dupuy, Stephen Hill and David Neubelt. BSD-2-Clause with a reference",
        "// to: Real-Time Polygonal-Light Shading with Linearly Transformed Cosines. Eric Heitz, Jonathan Dupuy, Stephen",
        "// Hill and David Neubelt. ACM Transactions on Graphics (Proceedings of ACM SIGGRAPH 2016) 35(4), 2016.",
        "// The licence text is in THIRD_PARTY_LICENSES.",
        "//",
        "// 64 x 64 texels, row by row (x: roughness, y: sqrt(1 - cos theta)). kLtcMatrix: the inverse matrix's x, y, z, w;",
        "// kLtcAmplitude: the lobe's magnitude and Fresnel term.",
        "// clang-format off",
        "inline constexpr float kLtcMatrix[64 * 64 * 4] = {",
    ]
    for i in range(SIZE * SIZE):
        lines.append(", ".join(literal(v) for v in m[4 * i : 4 * i + 4]) + ",")
    lines.append("};")
    lines.append("inline constexpr float kLtcAmplitude[64 * 64 * 2] = {")
    for i in range(SIZE * SIZE):
        lines.append(", ".join(literal(v) for v in g[4 * i : 4 * i + 2]) + ",")
    lines.append("};")
    lines.append("// clang-format on")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
